import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.ensemble import IsolationForest
from sklearn.neighbors import LocalOutlierFactor
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix
)

# 1. Generate normal training sensor data

np.random.seed(42)

sensor_names = [
    "Temperature",
    "Vibration",
    "Pressure",
    "Current"
]

normal_data = np.random.normal(
    loc=[60, 2.5, 5.0, 10.0],
    scale=[3, 0.5, 0.4, 1.0],
    size=(1500, 4)
)

# 2. Generate testing sensor data

test_data = np.random.normal(
    loc=[60, 2.5, 5.0, 10.0],
    scale=[3, 0.5, 0.4, 1.0],
    size=(1000, 4)
)

# 3. Introduce artificial anomalies

actual = np.zeros(1000, dtype=int)

anomaly_ranges = [
    (250, 330),
    (620, 700),
    (850, 900)
]

for start, end in anomaly_ranges:

    test_data[start:end, 0] += 18
    test_data[start:end, 1] += 3
    test_data[start:end, 2] -= 2
    test_data[start:end, 3] += 5

    actual[start:end] = 1

# 4. Convert data into DataFrames

train_df = pd.DataFrame(
    normal_data,
    columns=sensor_names
)

test_df = pd.DataFrame(
    test_data,
    columns=sensor_names
)

# 5. Standardize sensor readings

mean = train_df.mean()
std = train_df.std()

train_scaled = (train_df - mean) / std
test_scaled = (test_df - mean) / std

# 6. Isolation Forest

iso = IsolationForest(
    contamination=0.04,
    random_state=42
)

iso.fit(train_scaled)

iso_pred = (
    iso.predict(test_scaled) == -1
).astype(int)

# 7. Local Outlier Factor

lof = LocalOutlierFactor(
    n_neighbors=25,
    contamination=0.04,
    novelty=True
)

lof.fit(train_scaled)

lof_pred = (
    lof.predict(test_scaled) == -1
).astype(int)

# 8. Statistical anomaly detection

z_score = np.abs(
    (test_scaled - train_scaled.mean()) /
    train_scaled.std()
)

stat_pred = (
    z_score.max(axis=1) > 3.5
).astype(int)

# 9. Hybrid ensemble voting

votes = iso_pred + lof_pred + stat_pred

final_pred = (votes >= 2).astype(int)

# 10. Generate maintenance alerts

alerts = []

for i, prediction in enumerate(final_pred):

    if prediction == 1:

        if votes[i] == 3:
            level = "HIGH ALERT"

        else:
            level = "WARNING"

        alerts.append(level)

    else:
        alerts.append("NORMAL")

# 11. Display results

result_df = test_df.copy()

result_df["Actual"] = actual
result_df["Isolation_Forest"] = iso_pred
result_df["LOF"] = lof_pred
result_df["Statistical"] = stat_pred
result_df["Final_Prediction"] = final_pred
result_df["Maintenance_Status"] = alerts

print("\nHYBRID PREDICTIVE MAINTENANCE RESULTS")

print(result_df.head(15).to_string())

# 12. Evaluate model performance

print("\nMODEL PERFORMANCE")

print("Accuracy:",
      accuracy_score(actual, final_pred))

print("Precision:",
      precision_score(actual, final_pred,
                      zero_division=0))

print("Recall:",
      recall_score(actual, final_pred,
                   zero_division=0))

print("F1 Score:",
      f1_score(actual, final_pred,
               zero_division=0))

print("\nConfusion Matrix")

print(confusion_matrix(actual, final_pred))

# 13. Visualize sensor behaviour

plt.figure(figsize=(12, 5))

plt.plot(
    test_df["Vibration"],
    label="Vibration"
)

anomaly_indices = np.where(
    final_pred == 1
)[0]

plt.scatter(
    anomaly_indices,
    test_df.iloc[anomaly_indices]["Vibration"],
    color="red",
    label="Detected Anomaly"
)

plt.title("Hybrid Anomaly Detection in Machine Vibration")

plt.xlabel("Sensor Reading Index")
plt.ylabel("Vibration (mm/s)")

plt.legend()
plt.grid(True)
plt.tight_layout()

plt.show()

# 14. Display alert summary

print("\nMAINTENANCE ALERT SUMMARY")

print(result_df["Maintenance_Status"].value_counts())